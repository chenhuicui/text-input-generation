CREATE TABLE IF NOT EXISTS e2_abcdef_v2_runs (
    run_id CHAR(64) PRIMARY KEY,
    protocol_id VARCHAR(64) NOT NULL,
    run_scope VARCHAR(32) NOT NULL,
    source_run_dir TEXT NOT NULL,
    created_at_utc VARCHAR(40) NULL,
    config_sha256 CHAR(64) NULL,
    formal_run_enabled_at_start BOOLEAN NOT NULL,
    manifest_json LONGTEXT NOT NULL,
    smoke_acceptance_json LONGTEXT NULL,
    last_run_summary_json LONGTEXT NULL,
    last_run_elapsed_ms BIGINT NULL,
    first_synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_e2_v2_runs_protocol_scope (protocol_id, run_scope)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS e2_abcdef_v2_trajectories (
    run_id CHAR(64) NOT NULL,
    trajectory_id VARCHAR(128) NOT NULL,
    case_id VARCHAR(64) NOT NULL,
    task VARCHAR(32) NOT NULL,
    model VARCHAR(128) NOT NULL,
    representation VARCHAR(32) NOT NULL,
    arm CHAR(1) NOT NULL,
    state VARCHAR(16) NOT NULL,
    status VARCHAR(32) NULL,
    reason VARCHAR(128) NULL,
    budget INT NULL,
    first_success_turn INT NULL,
    model_calls INT NULL,
    executions INT NULL,
    recoveries INT NULL,
    analyzer_calls INT NULL,
    started_at_utc VARCHAR(40) NULL,
    completed_at_utc VARCHAR(40) NULL,
    elapsed_ms BIGINT NULL,
    dimensions_json LONGTEXT NOT NULL,
    events_json LONGTEXT NOT NULL,
    result_json LONGTEXT NULL,
    sqlite_updated_at VARCHAR(40) NULL,
    PRIMARY KEY (run_id, trajectory_id),
    UNIQUE INDEX uq_e2_v2_experimental_unit (run_id, model, case_id, arm),
    INDEX idx_e2_v2_traj_analysis (case_id, model, arm),
    INDEX idx_e2_v2_traj_status (status, reason),
    CONSTRAINT fk_e2_v2_traj_run FOREIGN KEY (run_id)
        REFERENCES e2_abcdef_v2_runs(run_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS e2_abcdef_v2_external_calls (
    run_id CHAR(64) NOT NULL,
    call_id VARCHAR(160) NOT NULL,
    kind VARCHAR(64) NOT NULL,
    state VARCHAR(16) NOT NULL,
    case_id VARCHAR(64) NULL,
    task VARCHAR(32) NULL,
    model VARCHAR(128) NULL,
    arm CHAR(1) NULL,
    turn_id INT NULL,
    role_name VARCHAR(64) NULL,
    response_id VARCHAR(255) NULL,
    session_id VARCHAR(255) NULL,
    response_model VARCHAR(128) NULL,
    run_status VARCHAR(32) NULL,
    error_type VARCHAR(128) NULL,
    elapsed_ms BIGINT NULL,
    provider_elapsed_seconds DOUBLE NULL,
    dimensions_json LONGTEXT NOT NULL,
    payload_json LONGTEXT NOT NULL,
    result_json LONGTEXT NULL,
    raw_query_json LONGTEXT NULL,
    raw_response_json LONGTEXT NULL,
    parsed_candidate_json LONGTEXT NULL,
    provider_response_json LONGTEXT NULL,
    usage_json LONGTEXT NULL,
    created_at_utc VARCHAR(40) NOT NULL,
    completed_at_utc VARCHAR(40) NULL,
    PRIMARY KEY (run_id, call_id),
    INDEX idx_e2_v2_calls_analysis (kind, case_id, model, arm, turn_id),
    INDEX idx_e2_v2_calls_session (session_id),
    INDEX idx_e2_v2_calls_status (state, run_status, error_type),
    CONSTRAINT fk_e2_v2_calls_run FOREIGN KEY (run_id)
        REFERENCES e2_abcdef_v2_runs(run_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

